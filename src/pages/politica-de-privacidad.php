                        <h2 id="priv-3-en">Purpose and Legal Basis for Processing</h2>
                        <p>We process your personal data on the basis of the <strong>free, express and informed consent</strong> you provide when contacting us or submitting your information, as well as on the other legal bases set out in applicable regulations (performance of a contractual or pre-contractual relationship and compliance with legal obligations). We will never use your data for purposes incompatible with those for which it was collected.</p>

                        <h2 id="priv-4-en">Data Retention</h2>
                        <p>We will retain your personal data only for as long as necessary to fulfil the purposes for which it was collected and, thereafter, for the applicable statutory retention periods (in particular, commercial, accounting, tax and labour matters). Once those periods have elapsed, the data will be securely deleted or anonymised.</p>

                        <h2 id="priv-5-en">Disclosures and International Transfers</h2>
                        <p>We do not sell, trade or assign your personal data to third parties unrelated to the operation.</p>
                        <p>We may share your information within the <strong>AMA Group</strong> —whose headquarters are located in Naples, Italy— where necessary for the provision of the service, operational management or the fulfilment of contractual obligations. We may also disclose your data to public authorities, supervisory bodies or third parties where a legal obligation or judicial requirement so demands.</p>
                        <p>Where a transfer involves sending data to other countries, we will adopt the safeguards required by Law No. 25.326 and its implementing regulations in order to guarantee an adequate level of protection for your information.</p>

                        <h2 id="priv-6-en">Security and Confidentiality</h2>
                        <p>We implement reasonable technical and organisational security measures to protect your data against unauthorised access, loss, alteration or destruction. Access to the information is restricted to authorised personnel who need to know it to fulfil the described purposes and who are bound by appropriate confidentiality obligations.</p>

                        <h2 id="priv-7-en">Rights of the Data Subject</h2>
                        <p>You have the right to exercise, free of charge, the rights of <strong>access, rectification, updating and deletion</strong> of your personal data, as well as to object to its processing under the terms of the applicable legislation.</p>
