                        </ul>

                        <h2 id="priv-2-es">Información que Recopilamos y su Origen</h2>
                        <p>Recopilamos datos personales únicamente cuando usted decide proporcionárnoslos de forma voluntaria a través de los siguientes canales:</p>

                        <h3>a. Contacto Comercial y Cotizaciones</h3>
                        <p>Al contactar a nuestro equipo Comercial (listado en las secciones "Servicios" y "Contacto") por correo electrónico o teléfono para solicitar cotizaciones o información.</p>
                        <ul>
                            <li><strong>Datos recopilados (ej.):</strong> nombre, apellido, correo electrónico, teléfono, empresa y detalles de la carga.</li>
                            <li><strong>Finalidad:</strong> responder a sus consultas, elaborar y enviar las cotizaciones solicitadas y gestionar la relación comercial.</li>
                        </ul>

                        <h3>b. Oportunidades de Carrera (Recursos Humanos)</h3>
                        <p>Al enviar su Currículum Vitae (CV) al correo de Recursos Humanos, ya sea para una vacante específica publicada en nuestra sección "Institucional" o de forma espontánea.</p>
                        <ul>
                            <li><strong>Datos recopilados (ej.):</strong> nombre, apellido, correo electrónico, teléfono, DNI, historial académico, experiencia laboral y cualquier otro dato incluido en su CV.</li>
                            <li><strong>Finalidad:</strong> evaluar su perfil profesional para procesos de selección actuales o futuros. Sus datos serán conservados en nuestra base de datos de candidatos.</li>
                        </ul>

                        <h3>c. Contacto Operativo y Documentación</h3>
                        <p>Al contactar a nuestros departamentos operativos (Documentación, Finanzas, Equipment &amp; Claims) para gestionar procedimientos.</p>
                        <ul>
                            <li><strong>Datos recopilados (ej.):</strong> datos del remitente, firmantes de cartas, información de BLs y datos de facturación.</li>
                            <li><strong>Finalidad:</strong> gestionar los procedimientos específicos de importación, exportación, facturación o reclamos.</li>
                        </ul>

                        <h3>d. Datos de Navegación (Cookies)</h3>
                        <p>Podemos recopilar datos de navegación de forma automática cuando utiliza nuestro sitio web. Para más detalles, consulte nuestra <a href="<?php echo BASE_URL; ?>politicas-de-cookies">Política de Cookies</a>.</p>

                        <h2 id="priv-3-es">Finalidad y Base de Licitud del Tratamiento</h2>
                        <p>Tratamos sus datos personales sobre la base del <strong>consentimiento libre, expreso e informado</strong> que usted presta al contactarnos o al remitir su información, así como sobre las demás bases de licitud previstas en la normativa vigente (ejecución de una relación contractual o precontractual y cumplimiento de obligaciones legales). En ningún caso utilizaremos sus datos para finalidades incompatibles con aquellas para las que fueron recabados.</p>

                        <h2 id="priv-4-es">Conservación de los Datos</h2>
                        <p>Conservaremos sus datos personales únicamente durante el tiempo necesario para cumplir con las finalidades para las que fueron recopilados y, posteriormente, durante los plazos legales de conservación que resulten aplicables (en particular, en materia comercial, contable, impositiva y laboral). Una vez cumplidos dichos plazos, los datos serán suprimidos o anonimizados de forma segura.</p>

                        <h2 id="priv-5-es">Cesiones y Transferencias Internacionales</h2>
                        <p>No vendemos, comercializamos ni cedemos sus datos personales a terceros ajenos a la operatoria.</p>
                        <p>Podremos compartir su información dentro del <strong>Grupo AMA</strong> —cuya casa matriz se encuentra en Nápoles, Italia— cuando ello resulte necesario para la prestación del servicio, la gestión operativa o el cumplimiento de obligaciones contractuales. Asimismo, podremos comunicar sus datos a autoridades públicas, organismos de control o terceros cuando exista una obligación legal o requerimiento judicial que así lo exija.</p>
                        <p>Cuando una transferencia implique el envío de datos a otros países, adoptaremos los recaudos exigidos por la Ley N° 25.326 y su normativa reglamentaria a fin de garantizar un nivel adecuado de protección de su información.</p>

                        <h2 id="priv-6-es">Seguridad y Confidencialidad</h2>
                        <p>Implementamos medidas de seguridad técnicas y organizativas razonables para proteger sus datos contra el acceso no autorizado, la pérdida, la alteración o la destrucción. El acceso a la información se encuentra restringido al personal autorizado que necesita conocerla para cumplir con las finalidades descriptas, quienes se encuentran obligados a mantener la debida confidencialidad.</p>

                        <h2 id="priv-7-es">Derechos del Titular de los Datos</h2>
                        <p>Usted tiene derecho a ejercer, de forma gratuita, los derechos de <strong>acceso, rectificación, actualización y supresión</strong> de sus datos personales, así como a oponerse a su tratamiento en los términos de la legislación vigente.</p>
                        <div class="legal-callout">
                            <h3>¿Cómo ejercer sus derechos?</h3>
                            <p>Envíe una solicitud por correo electrónico a <a href="mailto:AMA@ama-demo.example">AMA@ama-demo.example</a>, acreditando su identidad. Responderemos su requerimiento dentro de los plazos legales aplicables.</p>
                        </div>
                        <p>Se informa que la <strong>AGENCIA DE ACCESO A LA INFORMACIÓN PÚBLICA (AAIP)</strong>, en su carácter de Órgano de Control de la Ley N° 25.326, tiene la atribución de atender las denuncias y reclamos que se interpongan con relación al incumplimiento de las normas sobre protección de datos personales.</p>

                        <h2 id="priv-8-es">Menores de Edad</h2>
                        <p>Nuestro sitio web y nuestros servicios están dirigidos a personas mayores de edad. No recopilamos de forma intencional datos de menores de edad. Si tomamos conocimiento de que hemos recibido información de un menor sin la debida autorización, procederemos a su supresión.</p>

                        <h2 id="priv-9-es">Modificaciones a esta Política</h2>
                        <p>Nos reservamos el derecho de modificar la presente Política de Privacidad para adaptarla a novedades normativas, operativas o jurisprudenciales. Toda modificación será publicada en esta misma página, indicando su fecha de última actualización.</p>

